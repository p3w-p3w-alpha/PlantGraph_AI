import {test,expect} from '@playwright/test';

// Real image and investigation calls; not included unless explicitly requested.
test('live Gemma source-review to two independent Lower Fox engineering investigations',async({page,request})=>{
 test.skip(process.env.LIVE_AI!=='1','Set LIVE_AI=1 to make real Gemini API requests.');
 test.setTimeout(600000);
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await request.post('/api/cases/select',{data:{case_id:'lower-fox-river'}});
 await page.goto('/');
 await expect(page.locator('.asset-identity h2')).toHaveText('CF1');
 await page.getByRole('button',{name:'P&ID',exact:true}).click();
 const extractionResponse=page.waitForResponse(r=>r.url().endsWith('/api/ai/extract-demo')&&r.request().method()==='POST',{timeout:240000});
 await page.locator('.drawing-actions').getByRole('button',{name:'Extract scoped source with Gemma'}).click();
 const extraction=await(await extractionResponse).json();
 expect(extraction.source).toBe('gemma');expect(extraction.model).toBe('gemma-4-26b-a4b-it');
 expect(extraction.case_id).toBe('lower-fox-river');
 expect(extraction.assets.filter((a:any)=>a.type==='filter').length).toBeGreaterThanOrEqual(3);
 expect(extraction.assets.filter((a:any)=>a.type==='pump').length).toBeGreaterThanOrEqual(3);
 expect(extraction.assets.some((a:any)=>a.type==='tank')).toBe(true);
 await expect(page.getByRole('heading',{name:'Review the extracted plant.'})).toBeVisible();
 await page.screenshot({path:'../artifacts/lower-fox-live-extraction.png',fullPage:true});
 await page.getByRole('button',{name:'Use documented case mapping',exact:true}).click();
 await expect(page.getByText('Review these changes before confirming')).toBeVisible();
 const reviewResponse=page.waitForResponse(r=>r.url().endsWith('/api/ai/review')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Confirm reviewed model',exact:true}).click();
 const review=await(await reviewResponse).json();expect(review.simulation_ready).toBe(true);
 await expect(page.getByText('Reviewed source · active-case binding verified')).toBeVisible();
 const document=await(await request.get('/api/ai/documents/'+extraction.document_id)).json();
 expect(document.raw_extraction.assets).toEqual(extraction.assets);
 expect(document.review_provenance).toBe('source_reviewed_augmentation');
 await page.getByRole('button',{name:'Process graph',exact:true}).click();
 const canonical=await(await request.get('/api/plant')).json();
 const graphIds=await page.locator('.react-flow__node').evaluateAll(nodes=>nodes.map(n=>n.getAttribute('data-id')));
 expect(graphIds).toEqual(expect.arrayContaining(canonical.assets.map((a:any)=>a.id)));
 await page.getByRole('button',{name:'3D twin',exact:true}).click();
 const canvas=page.locator('.generic-twin canvas');await expect(canvas).toBeVisible();
 await expect.poll(async()=>Object.keys(JSON.parse(await canvas.getAttribute('data-asset-screen-positions')||'{}')).length).toBe(33);
 const normal=await(await request.get('/api/state')).json();
 expect(normal.metrics.mass_balance_m3h).toBeCloseTo(0,2);
 await page.getByRole('button',{name:'Play simulation',exact:true}).click();await page.waitForTimeout(1500);
 await page.getByRole('button',{name:'Pause simulation',exact:true}).click();
 for(const [scenario,asset,metric,sign] of [['filter_fouling','CF1','inflow_m3h',-1],['pump_degradation','P-2A','outflow_m3h',-1]] as const){
  await page.getByRole('combobox',{name:'Case scenario'}).selectOption(scenario);
  const operating=await(await request.get('/api/state')).json();
  expect(operating.elapsed_s).toBe(0);expect(operating.metrics.tank_level_m).toBe(normal.metrics.tank_level_m);
  expect(operating.metrics[metric]).toBeLessThan(normal.metrics[metric]);
  expect(operating.metrics.mass_balance_m3h*(scenario==='filter_fouling'?-1:1)).toBeGreaterThan(0);
  await page.locator('.tree-asset').filter({has:page.locator('strong',{hasText:new RegExp('^'+asset+'$')})}).click();
  const chatResponse=page.waitForResponse(r=>r.url().endsWith('/api/ai/chat')&&r.request().method()==='POST',{timeout:180000});
  await page.locator('.generic-twin').getByRole('button',{name:/Ask AI/}).click();
  const answer=await(await chatResponse).json();
  expect(answer.source).toBe('gemma');expect(answer.model).toBe('gemma-4-26b-a4b-it');
  expect(answer.evidence.length).toBeGreaterThan(1);expect(answer.hypotheses.length).toBeGreaterThan(0);
  await expect(page.locator('.evidence-list').last()).toBeVisible();
  await expect(page.locator('.assistant-text').last()).toContainText(/comput|simulat|model/i);
  await page.screenshot({path:`../artifacts/lower-fox-${scenario}-gemma.png`,fullPage:true});
  await page.locator('.generic-twin').getByRole('button',{name:/Test intervention/}).click();
  await expect(page.getByRole('heading',{name:'Test before you change.'})).toBeVisible();
  const row=page.locator('.compare-row').filter({hasText:scenario==='filter_fouling'?'filter bank inflow':'effluent outflow'});
  const values=await row.locator('strong').allTextContents();expect(parseFloat(values[1])).toBeGreaterThan(parseFloat(values[0]));
  const unchanged=await(await request.get('/api/state')).json();expect(unchanged).toEqual(operating);
  const interpretResponse=page.waitForResponse(r=>r.url().endsWith('/api/ai/chat')&&r.request().method()==='POST',{timeout:180000});
  await page.getByRole('button',{name:'Interpret with AI',exact:true}).click();
  const interpreted=await(await interpretResponse).json();expect(interpreted.source).toBe('gemma');expect(interpreted.evidence.length).toBeGreaterThan(0);
  await expect(page.locator('.assistant-text').last()).toContainText(/inflow|outflow|discharge|deliver|changeover/i);
 }
 expect(errors).toEqual([]);
 await page.getByRole('combobox',{name:'Engineering case'}).selectOption('atlas-station-01');
 await expect(page.locator('.asset-identity h2')).toHaveText('F-101');
 await expect(page.locator('.stat-value').first()).toContainText('69.4');
});
