"""Real EPANET snapshots with mass-conserving finite tank inventory.

The hydraulic operating point is solved, never generated by the language model.
Each snapshot is quasi-steady. Tank dynamics integrate pump outflow with a finite
inventory. No claim is made to model transients, treatment chemistry, or field
calibration. Session state is guarded because FastAPI runs sync routes in threads.
"""
from __future__ import annotations

from collections import deque
from copy import deepcopy
from datetime import datetime, timedelta, timezone
from pathlib import Path
from threading import RLock
import math
import tempfile
import time
import warnings

import wntr

from .schemas import Controls

ENGINE = 'EPANET 2.2 / WNTR'
ROOT = Path(__file__).resolve().parents[2]
BAR_PER_M = 0.0980665
TANK_AREA = math.pi * 3.0**2
MIN_LEVEL = 1.0
MAX_LEVEL = 6.0
LEVEL_EPS = 1e-5


def build_network(controls: Controls, level_m: float):
    wn = wntr.network.WaterNetworkModel()
    wn.options.time.duration = 0
    wn.options.time.hydraulic_timestep = 60
    wn.options.time.report_timestep = 60
    wn.options.hydraulic.headloss = 'H-W'
    wn.options.hydraulic.accuracy = 0.00001
    wn.options.hydraulic.trials = 100
    wn.options.hydraulic.emitter_exponent = 0.5
    wn.add_tank('T-101',elevation=0,init_level=max(MIN_LEVEL,min(MAX_LEVEL,level_m)),min_level=MIN_LEVEL,max_level=MAX_LEVEL,diameter=6,min_vol=0)
    for name in ['SUCTION','DISCHARGE','FILTER-IN','FILTER-OUT','VALVE-OUT','ISOLATION-IN']:
        wn.add_junction(name,base_demand=0,elevation=0)
    wn.add_reservoir('OUTLET',base_head=20)
    for name,a,b,length in [
        ('SUCTION-PIPE','T-101','SUCTION',8),
        ('DISCHARGE-PIPE','DISCHARGE','FILTER-IN',20),
        ('F-101','FILTER-IN','FILTER-OUT',0.1),
        ('DELIVERY-PIPE','VALVE-OUT','ISOLATION-IN',25),
        ('V-102','ISOLATION-IN','OUTLET',26.9),
    ]:
        wn.add_pipe(name,a,b,length=length,diameter=0.1,roughness=130,minor_loss=controls.filter_resistance if name=='F-101' else 0,initial_status='OPEN' if name!='V-102' or controls.outlet_open else 'CLOSED')
    # The health control belongs to pump A; pump B is the independent healthy
    # standby. Speed applies to the selected duty pump through affinity laws.
    enabled = controls.pump_speed_pct > 0 and level_m > MIN_LEVEL + LEVEL_EPS
    for pump in ['P-101A','P-101B']:
        head_scale = controls.pump_health_pct/100 if pump=='P-101A' else 1.0
        curve=f'{pump}-CURVE'
        wn.add_curve(curve,'HEAD',[(0,45*head_scale),(50/3600,35*head_scale),(100/3600,5*head_scale)])
        wn.add_pump(pump,'SUCTION','DISCHARGE',pump_type='HEAD',pump_parameter=curve,speed=max(0.01,controls.pump_speed_pct/100),initial_status='OPEN' if enabled and controls.active_pump==pump else 'CLOSED')
    opening = controls.valve_open_pct/100
    resistance = 5 + 200*(1-opening)**2
    wn.add_valve('V-101','FILTER-OUT','VALVE-OUT',diameter=0.1,valve_type='TCV',minor_loss=0,initial_setting=resistance,initial_status='ACTIVE' if opening>0 else 'CLOSED')
    if controls.leak_severity > 0:
        wn.get_node('VALVE-OUT').emitter_coefficient = 0.0015*controls.leak_severity/100
    return wn


def solve_hydraulics(controls: Controls,level_m: float):
    wn = build_network(controls,level_m)
    with tempfile.TemporaryDirectory(prefix='plantgraph-epanet-') as tmp:
        with warnings.catch_warnings(record=True) as captured:
            warnings.simplefilter('always')
            result = wntr.sim.EpanetSimulator(wn).run_sim(file_prefix=str(Path(tmp)/'snapshot'),version=2.2,convergence_error=True)
        pressures = result.node['pressure'].iloc[-1]
        heads = result.node['head'].iloc[-1]
        flows = result.link['flowrate'].iloc[-1]
        pump_outflow = max(0,float(flows['P-101A'])+float(flows['P-101B']))
        if pump_outflow<1e-6: pump_outflow=0.0
        delivery = float(flows['V-102'])
        leak = max(0,float(result.node['demand'].iloc[-1]['VALVE-OUT']))
        values = dict(
            tank_level_m=level_m,tank_level_pct=level_m/MAX_LEVEL*100,
            flow_m3h=delivery*3600,delivery_m3h=delivery*3600,
            pt101_bar=float(pressures['FILTER-IN'])*BAR_PER_M,
            pt102_bar=float(pressures['FILTER-OUT'])*BAR_PER_M,
            pump_speed_pct=controls.pump_speed_pct,valve_open_pct=controls.valve_open_pct,
            leak_m3h=leak*3600,pump_head_m=float(heads['DISCHARGE']-heads['SUCTION']) if controls.pump_speed_pct>0 and level_m>MIN_LEVEL+LEVEL_EPS else 0.0,
            filter_resistance=controls.filter_resistance,
        )
        values['filter_dp_bar'] = values['pt101_bar']-values['pt102_bar']
        if not all(math.isfinite(v) for v in values.values()):
            raise RuntimeError('Non-finite hydraulic solution')
        # EPANET can emit small numerical negative flows at closed links.
        for key in ['flow_m3h','delivery_m3h','leak_m3h']:
            if abs(values[key])<1e-3: values[key]=0.0
        messages = [str(w.message) for w in captured]
        return values,pump_outflow,'Converged hydraulic operating point' if not messages else 'Converged; '+ '; '.join(messages)[:180]


class SimulationService:
    def __init__(self):
        self.lock = RLock()
        self.controls = Controls()
        self.level_m = 4.0
        self.elapsed_s = 0.0
        self.playing = False
        self.speed = 30.0
        self.revision = 0
        self.base_time = datetime.now(timezone.utc)
        self.last_wall = time.monotonic()
        self.history = deque(maxlen=300)
        self.last_values = None
        self.pump_outflow_m3s = 0.0
        self.solver_ok = True
        self.solver_message = ''
        self._compute()
        self.baseline_flow = self.last_values['flow_m3h']
        self._record()
        model_dir = ROOT/'data'/'epanet'
        model_dir.mkdir(parents=True,exist_ok=True)
        if not (model_dir/'station.inp').exists():
            wntr.network.write_inpfile(build_network(self.controls,self.level_m),str(model_dir/'station.inp'),units='LPS',version=2.2)

    def _compute(self):
        if self.level_m<=MIN_LEVEL+LEVEL_EPS:
            self.level_m=MIN_LEVEL
        try:
            self.last_values,self.pump_outflow_m3s,self.solver_message = solve_hydraulics(self.controls,self.level_m)
            self.solver_ok = True
        except Exception as exc:
            if self.last_values is None:
                raise RuntimeError(f'Initial hydraulic solve failed: {exc}') from exc
            self.solver_ok = False
            self.solver_message = f'Hydraulic solve failed; retaining last valid readings: {str(exc)[:180]}'
            self.playing = False

    def _advance(self,force=False):
        now = time.monotonic()
        real_dt = max(0,now-self.last_wall)
        if not self.playing or not self.solver_ok:
            self.last_wall = now
            return
        # Keep the clock anchor when coalescing rapid reads, otherwise repeated
        # polls faster than 50 ms would silently discard all simulation time.
        if real_dt<0.05 and not force:
            return
        self.last_wall = now
        # A stalled browser cannot silently skip arbitrary hours. Up to 60 real
        # seconds are caught up per poll; simulation speed is always explicit.
        remaining = min(real_dt,60.0)*self.speed
        while remaining>1e-6 and self.playing:
            dt = min(remaining,30.0)
            available = max(0,(self.level_m-MIN_LEVEL)*TANK_AREA)
            used = min(available,self.pump_outflow_m3s*dt)
            if self.pump_outflow_m3s>0 and used<self.pump_outflow_m3s*dt:
                dt = used/self.pump_outflow_m3s
            self.level_m = max(MIN_LEVEL,self.level_m-used/TANK_AREA)
            self.elapsed_s += dt
            remaining -= dt
            self._compute()
            if self.level_m <= MIN_LEVEL+LEVEL_EPS:
                self.playing = False
            if dt<1e-9: break
        self._record()

    def _alarms(self):
        v = self.last_values
        alarms=[]
        def alarm(id,asset,severity,message,evidence):
            alarms.append(dict(id=id,asset_id=asset,severity=severity,message=message,evidence=evidence))
        if not self.solver_ok:
            alarm('solver-failed','OUTLET','critical','Hydraulic solution unavailable',[self.solver_message])
        if self.level_m<=MIN_LEVEL+LEVEL_EPS:
            alarm('tank-trip','T-101','critical','Low-low tank level: pump interlock active',[f'LT-101 {self.level_m:.2f} m; trip threshold {MIN_LEVEL:.2f} m'])
        elif self.level_m<1.5:
            alarm('tank-low','T-101','warning','Tank inventory approaching pump trip',[f'LT-101 {self.level_m:.2f} m; warning threshold 1.50 m'])
        if v['filter_dp_bar']>0.8:
            alarm('filter-dp','F-101','warning','High differential pressure across filter',[f'PT-101 {v["pt101_bar"]:.2f} bar',f'PT-102 {v["pt102_bar"]:.2f} bar',f'ΔP {v["filter_dp_bar"]:.2f} bar > 0.80 bar'])
        if hasattr(self,'baseline_flow') and v['delivery_m3h']<self.baseline_flow*0.78:
            alarm('delivery-low','OUTLET','warning','Distribution delivery below baseline',[f'FT-101 {v["delivery_m3h"]:.1f} m³/h',f'Baseline {self.baseline_flow:.1f} m³/h'])
        if v['leak_m3h']>0.5:
            alarm('mass-imbalance','V-101','warning','Unaccounted water between pumping and delivery',[f'Pump outflow {self.pump_outflow_m3s*3600:.1f} m³/h',f'Delivery {v["delivery_m3h"]:.1f} m³/h',f'Difference {v["leak_m3h"]:.1f} m³/h'])
        return alarms

    def _snapshot(self):
        c = self.controls
        running = c.pump_speed_pct>0 and self.level_m>MIN_LEVEL+LEVEL_EPS
        alarm_assets = {a['asset_id'] for a in self._alarms()}
        eq={
            'T-101':dict(status='alarm' if 'T-101' in alarm_assets else 'normal',mode='storage',value=self.level_m),
            'F-101':dict(status='warning' if 'F-101' in alarm_assets else 'normal',mode='filtration',value=self.last_values['filter_dp_bar']),
            'V-101':dict(status='closed' if c.valve_open_pct==0 else 'throttled' if c.valve_open_pct<95 else 'open',mode='manual',value=c.valve_open_pct),
            'V-102':dict(status='open' if c.outlet_open else 'closed',mode='manual',value=100 if c.outlet_open else 0),
            'OUTLET':dict(status='warning' if 'OUTLET' in alarm_assets else 'normal',mode='distribution',value=self.last_values['delivery_m3h']),
            'J-SUCTION':dict(status='normal',mode='junction'),
            'J-DISCHARGE':dict(status='normal',mode='junction'),
        }
        for pump in ['P-101A','P-101B']:
            eq[pump]=dict(status='running' if c.active_pump==pump and running else 'tripped' if c.active_pump==pump and self.level_m<=MIN_LEVEL+LEVEL_EPS else 'standby' if c.active_pump!=pump else 'stopped',mode='duty' if c.active_pump==pump else 'standby',value=c.pump_speed_pct if c.active_pump==pump and running else 0)
        return dict(timestamp=(self.base_time+timedelta(seconds=self.elapsed_s)).isoformat(),elapsed_s=self.elapsed_s,playing=self.playing,speed=self.speed,mode='simulation',engine=ENGINE,revision=self.revision,values=deepcopy(self.last_values),equipment=eq,alarms=self._alarms(),controls=c.model_dump(),provenance='Physics-generated demonstration · EPANET 2.2 · illustrative parameters · not field-calibrated',solver_ok=self.solver_ok,solver_message=self.solver_message)

    def _record(self):
        self.history.append(self._snapshot())

    def get_state(self,advance=True):
        with self.lock:
            if advance: self._advance()
            return deepcopy(self._snapshot())

    def get_history(self):
        with self.lock: return dict(points=deepcopy(list(self.history)))

    def action(self,action,speed=None):
        with self.lock:
            if action not in {'reset','play','pause','speed'}:
                raise ValueError('Unknown simulation action')
            if action=='speed' and speed is None:
                raise ValueError('Speed is required for the speed action')
            # Flush the old operating interval before pausing, changing speed,
            # or receiving a repeated play action. Reset intentionally discards
            # prior time because it defines a new initial-value problem.
            if action!='reset':self._advance(force=True)
            if action=='reset':
                self.controls=Controls(); self.level_m=4; self.elapsed_s=0;self.playing=False;self.revision+=1
                self.base_time=datetime.now(timezone.utc);self.history.clear();self._compute();self._record()
            elif action=='play':
                if self.level_m>MIN_LEVEL+LEVEL_EPS and self.solver_ok:self.playing=True
            elif action=='pause':self.playing=False
            elif action=='speed':
                self.speed=float(speed)
            self.last_wall=time.monotonic()
            if action!='reset':self._record()
            return self.get_state(advance=False)

    def update_controls(self,patch):
        with self.lock:
            controls=Controls.model_validate({**self.controls.model_dump(),**{k:v for k,v in patch.items() if v is not None}})
            # Elapsed time before this operator event belongs to the previous
            # controls, not the new valve/pump operating point.
            self._advance(force=True)
            self.controls=controls
            self.revision+=1;self._compute();self._record()
            return self.get_state(advance=False)

    def scenario(self,scenario,severity=0.7):
        with self.lock:
            if scenario not in {'baseline','filter_clogging','pump_degradation','valve_restriction','leak','low_tank'}:
                raise ValueError('Unknown scenario')
            self._advance(force=True)
            # Scenarios begin from the clean equipment settings but preserve the
            # clock and current tank inventory, except explicit low-level setup.
            c=Controls().model_dump()
            if scenario=='filter_clogging':c['filter_resistance']=10+100*severity
            elif scenario=='pump_degradation':c['pump_health_pct']=100-70*severity
            elif scenario=='valve_restriction':c['valve_open_pct']=max(0,100-95*severity)
            elif scenario=='leak':c['leak_severity']=100*severity
            elif scenario=='low_tank':self.level_m=1+0.4*(1-severity)
            self.controls=Controls.model_validate(c);self.revision+=1;self._compute();self._record()
            return self.get_state(advance=False)

    def what_if(self,patch):
        with self.lock:
            baseline=self.get_state(advance=False)
            controls=Controls.model_validate({**self.controls.model_dump(),**{k:v for k,v in patch.items() if v is not None}})
            try:
                values,outflow,message=solve_hydraulics(controls,self.level_m)
            except Exception as exc:
                raise RuntimeError(f'What-if hydraulic solve failed; live session unchanged: {str(exc)[:160]}') from exc
            predicted=deepcopy(baseline)
            predicted.update(values=values,controls=controls.model_dump(),solver_message=message,solver_ok=True,playing=False)
            # Build equipment and alarms using a detached, non-initialized clone
            # so predictions have no effect on the live session or model files.
            clone=object.__new__(SimulationService)
            clone.__dict__={**self.__dict__,'controls':controls,'last_values':values,'pump_outflow_m3s':outflow,'solver_message':message,'solver_ok':True,'playing':False}
            predicted=clone._snapshot()
            deltas={key:values[key]-baseline['values'][key] for key in values}
            summary=f'Delivery changes {deltas["delivery_m3h"]:+.1f} m³/h; filter ΔP changes {deltas["filter_dp_bar"]:+.2f} bar. Same tank level and downstream boundary; quasi-steady comparison.'
            return dict(baseline=baseline,predicted=predicted,deltas=deltas,summary=summary)


simulation_service = SimulationService()
